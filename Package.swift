// swift-tools-version: 6.0
import PackageDescription

// Burn Rate: an original brawler on the Randori engine (Vendor/randori, a path
// dependency: the engine uses unsafeFlags, which version-pinned dependencies reject).
func randori(_ product: String) -> Target.Dependency { .product(name: product, package: "randori") }

let package = Package(
    name: "BurnRate",
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "BurnRate", targets: ["BurnRateApp"]),
        .executable(name: "BurnRateHeadless", targets: ["BurnRateHeadless"]),
        .executable(name: "BurnRateContentBuilder", targets: ["BurnRateContentBuilder"]),
    ],
    dependencies: [.package(path: "Vendor/randori")],
    targets: [
        // The game's rules (shared by the builder, which records them in the identity, and the game).
        .target(name: "BurnRateRules", dependencies: [randori("RandoriCore")]),
        // The content identity generated by the builder; the packages themselves
        // live outside the repository (tools/build.sh) and reach the game through
        // the .app bundle or --resources.
        .target(name: "BurnRateContent", dependencies: ["BurnRateRules", randori("RandoriCore")]),
        .executableTarget(name: "BurnRateApp", dependencies: ["BurnRateContent", randori("RandoriAppKitHost")]),
        .executableTarget(name: "BurnRateHeadless", dependencies: ["BurnRateContent", randori("RandoriHeadlessHost")]),
        .executableTarget(name: "BurnRateContentBuilder", dependencies: ["BurnRateRules", randori("RandoriCore")]),
    ],
    swiftLanguageModes: [.v5]
)
